package project

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// Workspace-relative locations of the project templates written by za init
// and of the private project contexts instantiated from them.
const (
	templateDir = ".agents/context/_global/templates/project"
	contextDir  = ".agents/context/projects"
)

// contextFiles are the templates instantiated for every project. The ADR
// template is not among them: decisions/ starts empty.
var contextFiles = []string{"INDEX.md", "constraints.md", "source-of-truth.md", "status.md", "tools.md"}

// facts are the only project properties za knows for certain when it adds a
// project. Everything else stays a <discover: ...> or <decide: ...> placeholder.
type facts struct {
	ID       string
	Gitlink  string // full SHA of the staged submodule gitlink
	Date     string // YYYY-MM-DD
	OpenSpec bool   // <id>/openspec/ exists
	GoSum    bool   // <id>/go.sum exists
}

// readTemplates loads the project templates of the workspace at root.
func readTemplates(root string) (map[string][]byte, error) {
	out := make(map[string][]byte, len(contextFiles))
	for _, name := range contextFiles {
		rel := path.Join(templateDir, name)
		p := filepath.Join(root, filepath.FromSlash(rel))
		info, err := os.Lstat(p)
		if err == nil && !info.Mode().IsRegular() {
			err = errors.New("not a regular file")
		}
		if err != nil {
			return nil, fmt.Errorf("project template %s: %w", rel, err)
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("project template %s: %w", rel, err)
		}
		out[name] = data
	}
	return out, nil
}

// edit replaces text that must occur exactly once in a template after the
// <project-id> substitution.
type edit struct {
	file, old, new string
}

// renderContext instantiates the project templates for f. It fails if a
// template no longer has the shape za init generated, so that a known fact
// is never silently dropped.
func renderContext(templates map[string][]byte, f facts) (map[string][]byte, error) {
	out := make(map[string][]byte, len(templates))
	for name, data := range templates {
		out[name] = []byte(strings.ReplaceAll(string(data), "<project-id>", f.ID))
	}
	for _, e := range contextEdits(f) {
		s := string(out[e.file])
		if n := strings.Count(s, e.old); n != 1 {
			return nil, fmt.Errorf("project template %s/%s does not match the layout generated by za init: expected exactly one %q, found %d",
				templateDir, e.file, e.old, n)
		}
		out[e.file] = []byte(strings.Replace(s, e.old, e.new, 1))
	}
	return out, nil
}

func contextEdits(f facts) []edit {
	id := f.ID
	openspec := "`" + id + "/openspec/`"
	pending := "OpenSpec bootstrap pending (" + openspec + " does not exist yet)"
	goSum := "`" + id + "/go.sum`"
	if !f.GoSum {
		goSum = "not applicable"
	}

	edits := []edit{
		{"INDEX.md", "- Language/runtime: <discover: go | python-uv | mixed | other>", "- Language/runtime: go"},
		{"INDEX.md", "- Canonical workspace participation: <decide: go | uv | both | none>", "- Canonical workspace participation: go"},

		{"source-of-truth.md",
			"| Go dependencies | <discover: `" + id + "/go.mod` or not applicable> | Public | `" + id + "/go.sum` |",
			"| Go dependencies | `" + id + "/go.mod` | Public | " + goSum + " |"},
		{"source-of-truth.md", "<discover: `/go.work` or not applicable>", "`/go.work`"},

		{"tools.md",
			"| Go | <discover: yes/no> | <discover: version source and invocation> |",
			"| Go | yes | version source `" + id + "/go.mod`; <discover: invocation> |"},

		{"status.md", "- Phase: <decide: bootstrap | active-development | maintenance>", "- Phase: bootstrap"},
		{"status.md", "- Last verified: YYYY-MM-DD", "- Last verified: " + f.Date},
		{"status.md", "- Verified against gitlink: `<full-submodule-SHA>`", "- Verified against gitlink: `" + f.Gitlink + "`"},
	}

	issues := []string{"- Context bootstrap incomplete: `tools.md`, `constraints.md` and `source-of-truth.md` still hold discovery and decision placeholders."}
	steps := []string{
		"- Resolve the placeholders in `tools.md` and `source-of-truth.md` from the public repository.",
		"- Record only real, verifiable rules in `constraints.md`.",
	}
	if !f.OpenSpec {
		issues = append([]string{"- " + pending + "."}, issues...)
		steps = append([]string{"- Bootstrap OpenSpec in the public repository at " + openspec + "."}, steps...)
		edits = append(edits,
			edit{"INDEX.md", "- Public OpenSpec: " + openspec + "\n", "- Public OpenSpec: " + pending + "; never substitute private context for it\n"},
			edit{"source-of-truth.md", "| Current observable behavior | `" + id + "/openspec/specs/` |", "| Current observable behavior | " + pending + " |"},
			edit{"source-of-truth.md", "| Proposed behavior | `" + id + "/openspec/changes/<change>/` |", "| Proposed behavior | " + pending + " |"},
		)
	}
	edits = append(edits,
		edit{"status.md", "## Known issues\n\n- none\n", "## Known issues\n\n" + strings.Join(issues, "\n") + "\n"},
		edit{"status.md", "- <decide: at most three concrete items>", strings.Join(steps, "\n")},
	)
	return edits
}

// writeContext creates the private context directory of id under root. It
// never overwrites anything: the directory must not exist yet.
func writeContext(root, id string, files map[string][]byte) error {
	dir := filepath.Join(root, filepath.FromSlash(contextDir), id)
	if err := os.Mkdir(dir, 0o755); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	if err := os.Mkdir(filepath.Join(dir, "decisions"), 0o755); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	if err := writeNew(filepath.Join(dir, "decisions", ".gitkeep"), nil); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	for _, name := range contextFiles {
		if err := writeNew(filepath.Join(dir, name), files[name]); err != nil {
			return fmt.Errorf("create project context: %w", err)
		}
	}
	return nil
}

func writeNew(name string, content []byte) error {
	f, err := os.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	_, werr := f.Write(content)
	return errors.Join(werr, f.Close())
}

// exists reports whether p exists, without following a final symlink.
func exists(p string) (bool, error) {
	_, err := os.Lstat(p)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return err == nil, err
}
