package project

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// Workspace-relative locations of the project templates written by za init
// and of the private project contexts instantiated from them. Under the flat
// schema-4 layout both live directly under .agents/context/. The project
// guide is AGENTS.md; adr.md is the decision register and decisions/ holds
// the individual records. The decision record template itself is not
// instantiated: records are created by copying it when a decision is made.
const (
	templateDir = ".agents/context/templates/project"
	contextDir  = ".agents/context"
)

// contextFiles are the templates instantiated for every project. The
// decision record template is not among them: decisions/ starts empty.
var contextFiles = []string{"AGENTS.md", "adr.md", "sot.md", "status.md", "tools.md"}

// facts are the only project properties za knows for certain when it adds a
// project. Everything else stays a <discover: ...> or <decide: ...> placeholder.
type facts struct {
	ID       string
	Gitlink  string // full SHA of the staged submodule gitlink
	Date     string // YYYY-MM-DD
	OpenSpec bool   // <id>/openspec/ exists
	GoSum    bool   // <id>/go.sum exists
}

// readTemplates loads the project templates of the workspace at root.
func readTemplates(root string) (map[string][]byte, error) {
	out := make(map[string][]byte, len(contextFiles))
	for _, name := range contextFiles {
		rel := path.Join(templateDir, name)
		p := filepath.Join(root, filepath.FromSlash(rel))
		info, err := os.Lstat(p)
		if err == nil && !info.Mode().IsRegular() {
			err = errors.New("not a regular file")
		}
		if err != nil {
			return nil, fmt.Errorf("project template %s: %w", rel, err)
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("project template %s: %w", rel, err)
		}
		out[name] = data
	}
	return out, nil
}

// edit replaces text that must occur exactly once in a template after the
// <project-id> substitution.
type edit struct {
	file, old, new string
}

// renderContext instantiates the project templates for f. It fails if a
// template no longer has the shape za init generated, so that a known fact
// is never silently dropped: every template must name the project, and every
// known-fact placeholder must occur exactly once. User-authored content
// outside those substitution points is preserved byte for byte.
func renderContext(templates map[string][]byte, f facts) (map[string][]byte, error) {
	out := make(map[string][]byte, len(templates))
	for name, data := range templates {
		if !strings.Contains(string(data), "<project-id>") {
			return nil, fmt.Errorf("project template %s/%s does not match the layout generated by za init: expected the <project-id> substitution point", templateDir, name)
		}
		out[name] = []byte(strings.ReplaceAll(string(data), "<project-id>", f.ID))
	}
	for _, e := range contextEdits(f) {
		s := string(out[e.file])
		if n := strings.Count(s, e.old); n != 1 {
			return nil, fmt.Errorf("project template %s/%s does not match the layout generated by za init: expected exactly one %q, found %d",
				templateDir, e.file, e.old, n)
		}
		out[e.file] = []byte(strings.Replace(s, e.old, e.new, 1))
	}
	return out, nil
}

func contextEdits(f facts) []edit {
	id := f.ID
	goSum := "not applicable"
	if f.GoSum {
		goSum = "`" + id + "/go.sum`"
	}

	// OpenSpec is optional and its existence does not make it authoritative:
	// detection is recorded as a candidate, never as accepted authority.
	behaviorAuthority, behaviorCurrent, behaviorProposed := "unresolved", "unresolved", "unresolved"
	openSpecRow := "| OpenSpec | no | not adopted |"
	if f.OpenSpec {
		behaviorAuthority = "OpenSpec (detected; confirm authority)"
		behaviorCurrent = "`" + id + "/openspec/specs/`"
		behaviorProposed = "`" + id + "/openspec/changes/`"
		openSpecRow = "| OpenSpec | yes | <discover: CLI / agent skill> |"
	}

	edits := []edit{
		{"sot.md", "<discover: current behavior authority>", behaviorAuthority},
		{"sot.md", "<discover: current behavior location>", behaviorCurrent},
		{"sot.md", "<discover: proposed behavior authority>", behaviorAuthority},
		{"sot.md", "<discover: proposed behavior location>", behaviorProposed},
		{"sot.md", "<discover: `" + id + "/go.sum` or not applicable>", goSum},
		{"sot.md", "<discover: `/go.work` or not applicable>", "`/go.work`"},

		{"tools.md",
			"| Go | <discover: yes/no> | <discover: version source and invocation> |",
			"| Go | yes | version source `" + id + "/go.mod`; <discover: invocation> |"},
		{"tools.md",
			"| OpenSpec | <discover: yes/no> | <discover: CLI / agent skill / not adopted> |",
			openSpecRow},

		{"status.md", "- Phase: <decide: bootstrap | active-development | maintenance>", "- Phase: bootstrap"},
		{"status.md", "- Pin observed: YYYY-MM-DD", "- Pin observed: " + f.Date},
		{"status.md", "- Pinned gitlink: `<full-submodule-SHA>`", "- Pinned gitlink: `" + f.Gitlink + "`"},
		{"status.md", "- Verification summary: <decide: derived from the verification record; pending while no scope is verified>",
			"- Verification summary: pending (no scope verified; registration observed the pin)"},
		{"status.md", "## Known issues\n\n- none\n", "## Known issues\n\n" + strings.Join([]string{
			"- Context bootstrap incomplete: `tools.md` and `sot.md` still hold discovery and decision placeholders.",
			"- Context verification is pending: no scope has been verified against the recorded pin.",
		}, "\n") + "\n"},
		{"status.md", "- <decide: at most three concrete items>", strings.Join([]string{
			"- Resolve the placeholders in `tools.md` and `sot.md` from the project repository.",
			"- Declare the requirement authority for observable behavior in `sot.md`.",
			"- Run the documented commands and record review evidence in `status.md`.",
		}, "\n")},
	}
	return edits
}

// writeContext creates the private context directory of id under root. It
// never overwrites anything: the directory must not exist yet.
func writeContext(root, id string, files map[string][]byte) error {
	dir := filepath.Join(root, filepath.FromSlash(contextDir), id)
	if err := os.Mkdir(dir, 0o755); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	if err := os.Mkdir(filepath.Join(dir, "decisions"), 0o755); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	if err := writeNew(filepath.Join(dir, "decisions", ".gitkeep"), nil); err != nil {
		return fmt.Errorf("create project context: %w", err)
	}
	for _, name := range contextFiles {
		if err := writeNew(filepath.Join(dir, name), files[name]); err != nil {
			return fmt.Errorf("create project context: %w", err)
		}
	}
	return nil
}

func writeNew(name string, content []byte) error {
	f, err := os.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	_, werr := f.Write(content)
	return errors.Join(werr, f.Close())
}

// exists reports whether p exists, without following a final symlink.
func exists(p string) (bool, error) {
	_, err := os.Lstat(p)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return err == nil, err
}
